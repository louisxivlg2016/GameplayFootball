function detectLanguage(): AppLanguage {
  if (typeof window === "undefined") return "fr";
  const saved = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  if (saved && saved in translations) return saved as AppLanguage;
  const browser = navigator.language;
  if (browser in translations) return browser as AppLanguage;
  const prefix = LANGUAGE_OPTIONS.find((option) => browser.startsWith(option.code.split("-")[0]!));
  return prefix?.code ?? "fr";
}

function formatMessage(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return Object.entries(vars).reduce(
    (text, [key, value]) => text.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function translate(
  language: AppLanguage,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  return formatMessage(translations[language][key] ?? en[key], vars);
}

function normalizeBanner(text: string): string {
  return text.replaceAll("—", "-").replace(/\s+/g, " ").trim();
}

const bannerKeys: Partial<Record<string, TranslationKey>> = {
  "HORS-JEU": "bannerOffside",
  "HORS-JEU !": "bannerOffside",
  "⚠ HORS-JEU - RECULE": "bannerOffsideMoveBack",
  "✓ ONSIDE - BIEN !": "bannerOnsideGood",
};

export function translateBannerMessage(language: AppLanguage, text: string): string {
  const key = bannerKeys[normalizeBanner(text)];
  return key ? translate(language, key) : text;
}

export function translatePhaseLabel(language: AppLanguage, phaseLabel: string): string {
  switch (phaseLabel) {
    case "1ST":
      return translate(language, "phase1st");
    case "2ND":
      return translate(language, "phase2nd");
    case "ET1":
      return translate(language, "phaseEt1");
    case "ET2":
      return translate(language, "phaseEt2");
    case "PENS":
      return translate(language, "phasePens");
    case "ENTR.":
      return translate(language, "phasePractice");
    default:
      return phaseLabel;
  }
}

interface I18nValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: TranslationKey, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }): React.ReactNode {
  const [language, setLanguage] = useState<AppLanguage>(detectLanguage);

  useEffect(() => {
    if (typeof window === "undefined") return;
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);

  const value = useMemo<I18nValue>(
    () => ({
      language,
      setLanguage,
      t: (key, vars) => translate(language, key, vars),
    }),
    [language],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
